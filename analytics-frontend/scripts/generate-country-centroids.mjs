// Generates `src/lib/country-centroids.ts` from `country-centroids-source.csv`
// (ISO 3166-1 alpha-2 code, name, average lat/lng — sourced from
// https://gist.github.com/tadast/8827699, a widely-used public dataset).
// Machine-generated so the numbers are copied exactly, not retyped by hand.
// Re-run only if the source CSV changes; nothing else in the app depends on
// running this at build time.
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const csv = readFileSync(resolve(__dirname, "./country-centroids-source.csv"), "utf8")

// Proper CSV split: several country names embed a comma inside the quoted
// field (e.g. "Venezuela, Bolivarian Republic of"), so a naive `.split(",")`
// misaligns every column after it.
function splitCsvLine(line) {
  const cells = []
  let cell = ""
  let inQuotes = false
  for (const char of line) {
    if (char === '"') {
      inQuotes = !inQuotes
    } else if (char === "," && !inQuotes) {
      cells.push(cell.trim())
      cell = ""
    } else {
      cell += char
    }
  }
  cells.push(cell.trim())
  return cells
}

const rows = csv
  .trim()
  .split("\n")
  .slice(1)
  .map(splitCsvLine)

const seen = new Set()
const entries = []
for (const [name, alpha2, , , lat, lng] of rows) {
  if (seen.has(alpha2)) continue // dataset lists a couple of codes twice (e.g. Viet Nam / Vietnam)
  seen.add(alpha2)
  entries.push(`  ${alpha2}: { name: ${JSON.stringify(name)}, lat: ${lat}, lng: ${lng} },`)
}

const output = `// Generated by scripts/generate-country-centroids.mjs — do not edit by hand.
// ISO 3166-1 alpha-2 code -> country name + average lat/lng centroid.
// Used by \`analytics/realtime/realtime-map.tsx\` to place a pin per active
// country; matches the \`country_code char(2)\` column (Part 3 §3.3).
export interface CountryCentroid {
  name: string
  lat: number
  lng: number
}

export const COUNTRY_CENTROIDS: Record<string, CountryCentroid> = {
${entries.join("\n")}
}
`

writeFileSync(resolve(__dirname, "../src/lib/country-centroids.ts"), output)
console.log(`Wrote ${entries.length} country centroids.`)
